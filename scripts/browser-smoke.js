async (page) => {
  const check=(value,message)=>{if(!value)throw new Error(message);};
  const result=[];
  // Start from the observed dashboard and exercise the controls as a host would.
  await page.getByRole('button',{name:'진행 대시보드 Overview 01'}).click();
  await page.getByRole('button',{name:'두당 금액',exact:true}).click();
  await page.getByRole('spinbutton',{name:'임홍규 두당 금액'}).fill('300');
  await page.getByRole('spinbutton',{name:'임홍규 두당 금액'}).press('Tab');
  check(await page.locator('.stat-main .stat-value').innerText()==='300개','per funding conversion failed');
  await page.getByRole('button',{name:'후원 총액',exact:true}).click();
  check(await page.getByRole('spinbutton',{name:'임홍규 후원 총액'}).inputValue()==='1500','total must equal per * 5');
  await page.getByRole('button',{name:'실행 취소',exact:true}).click();
  check(await page.getByRole('spinbutton',{name:'임홍규 후원 총액'}).inputValue()==='1000','undo failed');
  result.push('funding totals / per-player conversion / undo');
  await page.reload();
  await page.getByRole('button',{name:'참가자 관리',exact:true}).waitFor();
  await page.getByRole('button',{name:'후원 총액',exact:true}).click();
  check(await page.getByRole('spinbutton',{name:'임홍규 후원 총액'}).inputValue()==='1000','reload persistence failed');
  await page.getByRole('button',{name:'참가자 관리',exact:true}).click();
  await page.getByRole('textbox',{name:'선수 이름 또는 별명 검색'}).fill('현제');
  check(await page.getByRole('img',{name:'변현제 프로필',exact:true}).count()>=2,'alias photo missing in library');
  await page.getByRole('textbox',{name:'선수 이름 또는 별명 검색'}).fill('김명운');
  await page.getByRole('button',{name:'김명운 참가 해제',exact:true}).click();
  await page.getByRole('button',{name:'라인업 적용',exact:true}).click();
  result.push('reload persistence / alias and portrait / roster selection');
  await page.getByRole('button',{name:'팀 편성 Match builder 02'}).click();
  await page.getByRole('button',{name:'무작위 팀 편성',exact:true}).click();
  check(await page.locator('.team-A .team-slot.filled').count()===5,'team A count');
  check(await page.locator('.team-B .team-slot.filled').count()===5,'team B count');
  await page.screenshot({path:'output/playwright/teams.png'});
  result.push('5:5 random teams');
  check(await page.getByRole('button',{name:'방송 화면 열기',exact:true}).count()===0,'output button removed');
  check(await page.locator('.right-rail').count()===0,'output side panel removed');
  result.push('full-width workspace without output controls');
  await page.getByRole('button',{name:'타이머 Time control 04'}).click();
  await page.getByRole('button',{name:'타이머 시작',exact:true}).click();
  await page.getByRole('button',{name:'일시정지',exact:true}).first().click();
  check((await page.locator('.timer-panel .clock-large').innerText()).startsWith('04:')||(await page.locator('.timer-panel .clock-large').innerText())==='05:00','timer display');
  result.push('timer start and pause');
  await page.getByRole('button',{name:'핀볼 & 룰렛 Draw studio 03'}).click();
  await page.getByRole('button',{name:'룰렛',exact:true}).click();
  await page.getByRole('button',{name:'추첨 시작',exact:true}).click();
  await page.locator('.draw-result strong').waitFor({timeout:15000});
  check(await page.locator('.ranking-list>div').count()===10,'wheel unique result count');
  result.push('roulette completes and records 10 ranks');
  await page.getByRole('button',{name:'핀볼',exact:true}).click();
  await page.getByRole('button',{name:'추첨 시작',exact:true}).click();
  await page.screenshot({path:'output/playwright/pinball-running.png'});
  await page.locator('.draw-result strong').waitFor({timeout:50000});
  check(await page.locator('.ranking-list>div').count()===10,'pinball result count');
  await page.screenshot({path:'output/playwright/draw-result.png'});
  result.push('physics pinball completes and records 10 ranks');
  return result;
}
