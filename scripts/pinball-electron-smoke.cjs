const { _electron } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const env = {...process.env, PLSET_TEST:'1', PLSET_TEST_DATA:path.join(root,'output',`pinball-native-${Date.now()}`)};
delete env.ELECTRON_RUN_AS_NODE;
let app;
(async()=>{
  app=await _electron.launch({executablePath:path.join(root,'release-build/win-unpacked/PLSet.exe'),cwd:root,env,timeout:30000});
  const page=await app.firstWindow();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.getByRole('button',{name:'참가자 관리',exact:true}).waitFor();
  await page.evaluate(()=>document.fonts.ready);
  const funding=await page.locator('.funding-panel').boundingBox();
  assert.ok(funding.y+funding.height<=await page.evaluate(()=>innerHeight),'10-player funding panel fits native window');
  assert.equal(await page.locator('.funding-observer-cutoff .row-index').innerText(),'04');
  const fundingInputs=page.locator('.funding-table .amount-input input');
  await fundingInputs.nth(3).fill('123');await fundingInputs.nth(3).press('Enter');
  await page.waitForFunction(()=>document.activeElement===document.querySelectorAll('.funding-table .amount-input input')[3]);
  await page.getByRole('button',{name:'핀볼 Pinball 03',exact:true}).click();
  const stageBounds=await page.locator('.stage-panel:visible').boundingBox();
  assert.ok(stageBounds.y+stageBounds.height<=await page.evaluate(()=>innerHeight),'full pinball stage fits native window');
  assert.equal(await page.evaluate(()=>typeof window.advanceTime),'undefined','development time hooks absent in packaged app');
  await page.getByRole('button',{name:'배치 섞기',exact:true}).click();
  await page.getByRole('button',{name:'추첨 시작',exact:true}).click();
  await page.getByRole('button',{name:'추첨 취소',exact:true}).waitFor();
  await page.waitForTimeout(4500);
  assert.ok(await page.locator('.pinball-marble-name:visible').count()>0,'native sharp names visible');
  await page.locator('.pinball-canvas').screenshot({path:path.join(root,'output/playwright/pinball-native-countdown.png')});
  await page.getByRole('heading',{name:'추첨 순위',exact:true}).waitFor({timeout:180000});
  assert.equal(await page.locator('.ranking-list > div').count(),10);
  const {state}=await page.evaluate(()=>window.plset.load());
  assert.equal(state.draw.results.length,10);
  assert.equal(new Set(state.draw.results).size,10);
  await page.locator('.pinball-canvas').screenshot({path:path.join(root,'output/playwright/pinball-native-complete.png')});
  await page.getByRole('combobox',{name:'모드',exact:true}).selectOption('ace');
  await page.getByRole('spinbutton',{name:'극락 수량',exact:true}).fill('5');
  await page.getByRole('button',{name:'추첨 시작',exact:true}).click();
  await page.getByRole('heading',{name:'추첨 순위',exact:true}).waitFor({timeout:180000});
  const aceState=await page.evaluate(()=>window.plset.load());
  assert.equal(aceState.state.draw.variant,'ace');
  assert.equal(aceState.state.draw.results.length,15);
  assert.deepEqual([...new Set(aceState.state.draw.items.map(i=>i.label))],['극락','나락','자연']);
  await page.locator('.pinball-canvas').screenshot({path:path.join(root,'output/playwright/pinball-native-ace.png')});
  await page.getByRole('combobox',{name:'모드',exact:true}).selectOption('players');
  await page.getByRole('combobox',{name:'추첨 대상',exact:true}).selectOption('A');
  const members=state.players.filter(p=>p.active).slice(0,5);
  for(const p of members)await page.locator('.draw-team-picker button').filter({hasText:p.name}).click();
  await page.getByRole('button',{name:'선택 완료',exact:true}).click();
  await page.getByRole('spinbutton',{name:members[0].name+' 수량',exact:true}).fill('2');
  await page.getByRole('spinbutton',{name:members[1].name+' 수량',exact:true}).fill('0');
  await page.getByRole('button',{name:'추첨 시작',exact:true}).click();
  await page.getByRole('heading',{name:'추첨 순위',exact:true}).waitFor({timeout:180000});
  const weighted=await page.evaluate(()=>window.plset.load());
  assert.equal(weighted.state.draw.results.length,5);
  assert.equal(weighted.state.draw.counts[members[1].id],0);
  assert.ok(weighted.state.draw.items.every(i=>i.playerId!==members[1].id));
  assert.deepEqual(errors,[]);
  await app.close();app=null;
  console.log(JSON.stringify({passed:['packaged launch','countdown','physical race finishes','10 unique results saved through IPC','no development hooks','observer cutoff','Enter retains rank focus','native sharp moving names','ACE 15-ball and weighted team physical races with IPC','no page errors']}));
})().catch(async e=>{console.error(e);if(app)await app.close();process.exitCode=1;});
